import type { AnalysisResult } from '../types/index.ts';

export function generateMarkdownReport(result: AnalysisResult): string {
  const dateStr = new Date(result.timestamp).toUTCString();
  const modeNames: Record<string, string> = {
    seance: 'Séance (Atmospheric Narrative & Archeology)',
    autopsy: 'Autopsy (Vulnerability & Pattern Investigation)',
    resurrection: 'Resurrection (Modernization & Migration)',
  };

  let md = `# THE LAST COMMIT — CODE ARCHEOLOGY REPORT
> "Every codebase leaves a trace. Some refuse to disappear."

- **Subject**: ${result.title}
- **Language**: ${result.language}
- **Analysis Mode**: ${modeNames[result.mode] || result.mode}
- **Timestamp**: ${dateStr}
- **Model Engine**: ${result.modelUsed || 'Gemma 4 (gemma-4-26b-a4b-it)'}
- **Confidence Rating**: ${result.confidence.toUpperCase()}
${result.isSample ? '- **Notice**: Archival prewritten demonstration\n' : ''}

---

## 1. Technical Summary
${result.summary}

`;

  if (result.ghostWhisper) {
    md += `## 2. The Ghost's Whisper
> *${result.ghostWhisper}*

`;
  }

  if (result.findings && result.findings.length > 0) {
    md += `## 3. Autopsy & Pattern Findings
`;
    result.findings.forEach((f, idx) => {
      md += `### 3.${idx + 1} [${f.severity.toUpperCase()}] ${f.title}\n`;
      if (f.excerpt) {
        md += `\`\`\`${result.language.toLowerCase()}\n${f.excerpt}\n\`\`\`\n`;
      }
      md += `**Observation**: ${f.description}\n\n`;
      if (f.remediation) {
        md += `**Remediation**: ${f.remediation}\n\n`;
      }
    });
  }

  if (result.modernizedCode) {
    md += `## 4. Modernized Resurrection
\`\`\`${result.language.toLowerCase()}
${result.modernizedCode}
\`\`\`

`;
  }

  if (result.explanations && result.explanations.length > 0) {
    md += `## 5. Key Architecture & Pattern Changes
`;
    result.explanations.forEach(exp => {
      md += `- ${exp}\n`;
    });
    md += '\n';
  }

  if (result.caveats && result.caveats.length > 0) {
    md += `## 6. Compatibility Caveats & Unknowns
`;
    result.caveats.forEach(cav => {
      md += `- ⚠️ ${cav}\n`;
    });
    md += '\n';
  }

  if (result.suggestedTests && result.suggestedTests.length > 0) {
    md += `## 7. Recommended Test Cases
`;
    result.suggestedTests.forEach(t => {
      md += `- [ ] ${t}\n`;
    });
    md += '\n';
  }

  md += `---

## 8. Original Code Snippet Analyzed
\`\`\`${result.language.toLowerCase()}
${result.originalCode}
\`\`\`

*Report generated by The Last Commit — Open-Weight AI Code Archaeologist*
`;

  return md;
}

export function downloadMarkdownFile(filename: string, content: string): void {
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}
